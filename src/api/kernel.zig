pub const ResolvedModel = struct {
    repo: []const u8, // Hugging Face repo (e.g. "bartowski/Qwen2.5-7B-Instruct-GGUF")
    file: []const u8, // GGUF filename within the repo
};

// =============================================================================
//  ░░░  USER CONTRIBUTION POINT  ░░░
//
//  Pick the canonical GGUFs that ship as Wintermolt's defaults. Anything not
//  in this map can still be loaded by absolute path or by dropping a file
//  into ~/.wintermolt/models/<alias>.gguf — but the aliases below are what
//  `/model kernel gemma3` and friends will resolve to out-of-the-box.
//
//  Considerations:
//    - Q4_K_M is the usual quality/size sweet spot on Apple Silicon
//    - Gemma 3 4B Q4_K_M ≈ 2.5GB; Gemma 3 12B Q4_K_M ≈ 7GB
//    - Qwen 3 8B Q4_K_M ≈ 5GB; Qwen 3 0.6B ≈ 400MB (good for testing)
//    - Reputable repos: unsloth/, bartowski/, ggml-org/, lmstudio-community/
//
//  Return null for an unrecognized alias — the caller falls through to the
//  local-file lookup before giving up.
// =============================================================================
pub fn resolveAlias(alias: []const u8) ?ResolvedModel {
    // Built-in defaults (David: replace/extend with curated repos):
    if (std.mem.eql(u8, alias, "qwen3:0.6b"))
        return .{ .repo = "Qwen/Qwen2.5-0.5B-Instruct-GGUF", .file = "qwen2.5-0.5b-instruct-q4_k_m.gguf" };
    return null;
}

/// Resolve `/model kernel <alias>` to a concrete GGUF path. Lookup order:
///   1. Absolute or ~-prefixed path → use as-is
///   2. <model_dir>/<alias>.gguf
///   3. <model_dir>/<alias>/*.gguf (first match)
///   4. Alias map → print download hint, return ModelNotFound
pub fn resolveModelPath(alloc: Allocator, alias: []const u8, model_dir: []const u8) ![]const u8 {
    if (alias.len == 0) return Error.ModelNotFound;

    // 1. Absolute or home-prefixed
    if (alias[0] == '/' or alias[0] == '~') {
        return try expandHome(alloc, alias);
    }

    // 2. <model_dir>/<alias>.gguf
    {
        const direct = try std.fmt.allocPrint(alloc, "{s}/{s}.gguf", .{ model_dir, alias });
        if (std.fs.cwd().access(direct, .{})) |_| {
            return direct;
        } else |_| {
            alloc.free(direct);
        }
    }

    // 3. <model_dir>/<alias>/*.gguf
    {
        const subdir = try std.fmt.allocPrint(alloc, "{s}/{s}", .{ model_dir, alias });
        defer alloc.free(subdir);
        if (std.fs.cwd().openDir(subdir, .{ .iterate = true })) |dir_const| {
            var dir = dir_const;
            defer dir.close();
            var it = dir.iterate();
            while (try it.next()) |entry| {
                if (entry.kind == .file and std.mem.endsWith(u8, entry.name, ".gguf")) {
                    return try std.fmt.allocPrint(alloc, "{s}/{s}", .{ subdir, entry.name });
                }
            }
        } else |_| {}
    }

    // 4. Alias map → download hint
    if (resolveAlias(alias)) |resolved| {
        const stderr = std.fs.File.stderr().deprecatedWriter();
        stderr.print(
            "[kernel] Model '{s}' not found locally.\n  Download with:\n    huggingface-cli download {s} {s} --local-dir {s}/{s}\n",
            .{ alias, resolved.repo, resolved.file, model_dir, alias },
        ) catch {};
    } else {
        const stderr = std.fs.File.stderr().deprecatedWriter();
        stderr.print(
            "[kernel] Unknown model alias '{s}'. Drop a GGUF at {s}/{s}.gguf or extend resolveAlias() in src/api/kernel.zig.\n",
            .{ alias, model_dir, alias },
        ) catch {};
    }

    return Error.ModelNotFound;
}

fn expandHome(alloc: Allocator, path: []const u8) ![]const u8 {
    if (path.len == 0 or path[0] != '~') return try alloc.dupe(u8, path);
    const home = std.posix.getenv("HOME") orelse return try alloc.dupe(u8, path);
    if (path.len == 1) return try alloc.dupe(u8, home);
    if (path[1] != '/') return try alloc.dupe(u8, path);
    return try std.fmt.allocPrint(alloc, "{s}{s}", .{ home, path[1..] });
}

/// Default model directory: $WINTERMOLT_KERNEL_MODEL_DIR or ~/.wintermolt/models
pub fn defaultModelDir(alloc: Allocator) ![]const u8 {
    if (std.posix.getenv("WINTERMOLT_KERNEL_MODEL_DIR")) |dir| {
        return try alloc.dupe(u8, dir);
    }
    const home = std.posix.getenv("HOME") orelse return Error.ModelNotFound;
    return try std.fmt.allocPrint(alloc, "{s}/.wintermolt/models", .{home});
}
